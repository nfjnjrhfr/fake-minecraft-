export const MODE_IDS = Object.keys(MODES);

export function getMode(id) {
  return MODES[id] || MODES.chat;
}

/** 給前端用的模式清單（不含冗長的系統提示）。 */
export function modeCatalog() {
  return MODE_IDS.map((id) => ({
    id,
    label: MODES[id].label,
    group: MODES[id].group,
    icon: MODES[id].icon,
    hint: MODES[id].hint,
  }));
}

/**
 * 組出系統提示。放在最前面的是不會變動的內容，方便 prompt caching 命中。
 */
export function buildSystem(modeId, { today, userNote } = {}) {
  const mode = getMode(modeId);
  const blocks = [
    { type: 'text', text: BASE_SYSTEM },
    { type: 'text', text: mode.system },
  ];
  const context = [];
  if (today) context.push(`今天是 ${today}（使用者裝置時間）。計算相對日期時以此為準。`);
  if (userNote) context.push(`使用者的長期偏好：${userNote}`);
  if (context.length) blocks.push({ type: 'text', text: context.join('\n') });
  // 快取到最後一個穩定區塊，重複對話時省下輸入成本
  blocks[blocks.length - 1].cache_control = { type: 'ephemeral' };
  return blocks;
}

export function defaultTask(modeId) {
  return getMode(modeId).task;
}
