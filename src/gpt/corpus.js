// 顏色
const colors = [
  ['草地', '綠色'], ['天空', '藍色'], ['岩漿', '紅色'], ['鑽石', '青色'],
  ['木頭', '棕色'], ['石頭', '灰色'], ['太陽', '黃色'], ['雪', '白色'], ['夜晚', '黑色'],
];
for (const [thing, color] of colors) {
  add(`${thing}是什麼顏色`, `${thing}是${color}的。`);
  add(`什麼是${color}的`, `${thing}是${color}的。`);
}

// 加法與減法（讓它學會一種有規則的對應關係）
for (let a = 0; a <= 9; a++) {
  for (let b = 0; b <= 9; b++) {
    add(`${num2cn(a)}加${num2cn(b)}等於多少`, `${num2cn(a)}加${num2cn(b)}等於${num2cn(a + b)}。`);
    if (a >= b) add(`${num2cn(a)}減${num2cn(b)}等於多少`, `${num2cn(a)}減${num2cn(b)}等於${num2cn(a - b)}。`);
  }
}

// 比大小
for (let a = 0; a <= 9; a++) {
  for (let b = 0; b <= 9; b++) {
    if (a === b) continue;
    add(`${num2cn(a)}和${num2cn(b)}哪個大`, `${num2cn(Math.max(a, b))}比${num2cn(Math.min(a, b))}大。`);
  }
}

// 數數
for (let a = 0; a <= 9; a++) add(`${num2cn(a)}後面是什麼`, `${num2cn(a)}後面是${num2cn(a + 1)}。`);

// 覆誦
