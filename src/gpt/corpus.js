const CN = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];

/** 把 0~20 的數字寫成中文 */
export function num2cn(n) {
  if (n <= 10) return CN[n];
  if (n < 20) return '十' + CN[n - 10];
  return '二十';
}

